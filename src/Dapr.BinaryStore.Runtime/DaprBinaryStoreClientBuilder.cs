using Dapr.Common;
using Microsoft.Extensions.Configuration;
using Autogenerated = Dapr.Client.Autogen.Grpc.v1;

namespace Dapr.BinaryStore;

/// <summary>
/// Builds a <see cref="DaprBinaryStoreClient"/>.
/// </summary>
/// <remarks>
/// Use this builder when you need to create a <see cref="DaprBinaryStoreClient"/> manually,
/// outside of dependency injection. For DI-based scenarios, use
/// <c>DaprBinaryStoreServiceCollectionExtensions.AddDaprBinaryStoreClient</c> instead.
/// </remarks>
/// <param name="configuration">
/// An optional <see cref="IConfiguration"/> instance used to read Dapr defaults such as the
/// API token and endpoint addresses from the environment.
/// </param>
public sealed class DaprBinaryStoreClientBuilder(IConfiguration? configuration = null)
    : DaprGenericClientBuilder<DaprBinaryStoreClient>(configuration)
{
    /// <summary>
    /// Builds a new <see cref="DaprBinaryStoreClient"/> from the current builder configuration.
    /// </summary>
    /// <returns>A configured <see cref="DaprBinaryStoreClient"/> instance.</returns>
    public override DaprBinaryStoreClient Build()
    {
        var deps = this.BuildDaprClientDependencies(typeof(DaprBinaryStoreClient).Assembly);
        var grpcClient = new Autogenerated.Dapr.DaprClient(deps.channel);
        return new DaprBinaryStoreGrpcClient(grpcClient, deps.httpClient, deps.daprApiToken);
    }
}
