using Grpc.Core;
using Autogenerated = Dapr.Client.Autogen.Grpc.v1;

namespace Dapr.Cryptography.Encryption;

/// <summary>
/// Provides the implementation to decrypt a stream of ciphertext data with the Dapr runtime.
/// </summary>
internal sealed class DecryptionStreamProcessor :
    DuplexStreamProcessor<Autogenerated.DecryptRequest, Autogenerated.DecryptResponse>, IDecryptionStreamProcessor
{
    public Task ProcessStreamAsync(
        Stream inputStream,
        AsyncDuplexStreamingCall<Autogenerated.DecryptRequest, Autogenerated.DecryptResponse> call,
        int streamingBlockSizeInBytes,
        Autogenerated.DecryptRequestOptions options,
        CancellationToken cancellationToken)
    {
        return StartProcessing(inputStream, call, streamingBlockSizeInBytes,
            (data, sequenceNumber) => new Autogenerated.DecryptRequest
            {
                Payload = new Autogenerated.StreamPayload { Data = data, Seq = sequenceNumber },
                Options = sequenceNumber == 0 ? options : null
            },
            response => response.Payload.Data.Memory, cancellationToken);
    }
}
