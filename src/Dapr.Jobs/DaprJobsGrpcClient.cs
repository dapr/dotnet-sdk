using Dapr.Common;
using Dapr.Jobs.Models;
using Dapr.Jobs.Models.Responses;
using Google.Protobuf;
using Google.Protobuf.WellKnownTypes;
using Grpc.Core;
using Autogenerated = Dapr.Client.Autogen.Grpc.v1;

namespace Dapr.Jobs;

/// <summary>
/// A client for interacting with the Dapr endpoints.
/// </summary>
internal sealed class DaprJobsGrpcClient(Autogenerated.Dapr.DaprClient client, HttpClient httpClient, IDaprRuntimeCapabilities runtimeCapabilities, string? daprApiToken = null) : DaprJobsClient(client, httpClient, daprApiToken: daprApiToken)
{
    /// <summary>
    /// Version-aware wrapper that automatically falls back to Alpha1 gRPC variants
    /// when the connected Dapr runtime does not yet support the stable API.
    /// </summary>
    private readonly IVersionAwareDaprClient _versionAwareClient = new VersionAwareDaprClient(client, runtimeCapabilities);

    /// <summary>
    /// Schedules a job with Dapr.
    /// </summary>
    /// <param name="jobName">The name of the job being scheduled.</param>
    /// <param name="schedule">The schedule defining when the job will be triggered.</param>
    /// <param name="payload">The main payload of the job.</param>
    /// <param name="startingFrom">The optional point-in-time from which the job schedule should start.</param>
    /// <param name="repeats">The optional number of times the job should be triggered.</param>
    /// <param name="ttl">Represents when the job should expire. If both this and DueTime are set, TTL needs to represent a later point in time.</param>
    /// <param name="overwrite">A flag indicating whether the job should be overwritten when submitted (true); otherwise false to require that an existing job with the same name be deleted first.</param>
    /// <param name="failurePolicyOptions">The characteristics of the policy to apply when a job fails to trigger.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    public override async Task ScheduleJobAsync(string jobName, DaprJobSchedule schedule,
        ReadOnlyMemory<byte>? payload = null, DateTimeOffset? startingFrom = null, int? repeats = null,
        DateTimeOffset? ttl = null, bool overwrite = false, IJobFailurePolicyOptions? failurePolicyOptions = null,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(jobName);
        ArgumentNullException.ThrowIfNull(schedule);

        var job = new Autogenerated.Job { Name = jobName };

        //Set up the schedule (recurring or point in time)
        if (schedule.IsPointInTimeExpression)
        {
            job.DueTime = schedule.ExpressionValue;
        }
        else if (schedule.IsCronExpression || schedule.IsPrefixedPeriodExpression || schedule.IsDurationExpression)
        {
            job.Schedule = schedule.ExpressionValue;
        }
        
        if (startingFrom is not null)
        {
            job.DueTime = ((DateTimeOffset)startingFrom).ToString("O");
        }
        
        if (repeats is not null)
        {
            if (repeats < 0)
            {
                throw new ArgumentOutOfRangeException(nameof(repeats));
            }

            job.Repeats = (uint)repeats;
        }

        if (payload is not null)
        {
            job.Data = new Any { Value = ByteString.CopyFrom(payload.Value.Span), TypeUrl = "dapr.io/schedule/jobpayload" };
        }

        if (ttl is not null)
        {
            if (ttl <= startingFrom)
            {
                throw new ArgumentException(
                    $"When both {nameof(ttl)} and {nameof(startingFrom)} are specified, {nameof(ttl)} must represent a later point in time");
            }

            job.Ttl = ((DateTimeOffset)ttl).ToString("O");
        }

        if (failurePolicyOptions is not null)
        {
            switch (failurePolicyOptions.Policy)
            {
                case JobFailurePolicy.Drop:
                    job.FailurePolicy = new Autogenerated.JobFailurePolicy
                    {
                        Drop = new Autogenerated.JobFailurePolicyDrop()
                    };
                    break;
                case JobFailurePolicy.Constant:
                    var constantOptions = (JobFailurePolicyConstantOptions)failurePolicyOptions;
                    if (constantOptions.MaxRetries is null)
                    {
                        job.FailurePolicy = new Autogenerated.JobFailurePolicy
                        {
                            Constant = new Autogenerated.JobFailurePolicyConstant
                            {
                                Interval = constantOptions.Interval.ToDuration()
                            }
                        };
                    }
                    else
                    {
                        job.FailurePolicy = new Autogenerated.JobFailurePolicy
                        {
                            Constant = new Autogenerated.JobFailurePolicyConstant
                            {
                                Interval = constantOptions.Interval.ToDuration(),
                                MaxRetries = (uint)constantOptions.MaxRetries
                            }
                        };
                    }
                    break;
            }
        }

        var envelope = new Autogenerated.ScheduleJobRequest { Job = job, Overwrite = overwrite };

        var grpcCallOptions = DaprClientUtilities.ConfigureGrpcCallOptions(typeof(DaprJobsClient).Assembly, this.DaprApiToken, cancellationToken);

        try
        {
            await _versionAwareClient.ScheduleJobAsync(envelope, grpcCallOptions).ConfigureAwait(false);
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
            //Ignore our own cancellation
        }
        catch (RpcException ex) when (ex.StatusCode == StatusCode.Cancelled && cancellationToken.IsCancellationRequested)
        {
            // Ignore a remote cancellation due to our own cancellation
        }
        catch (Exception ex)
        {
            throw new DaprException(
                "Schedule job operation failed: the Dapr endpoint indicated a failure. See InnerException for details.",
                ex);
        }
    }

    /// <summary>
    /// Retrieves the details of a registered job.
    /// </summary>
    /// <param name="jobName">The name of the job.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>The details comprising the job.</returns>
    public override async Task<DaprJobDetails> GetJobAsync(string jobName, CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(jobName);
        
        try
        {
            var envelope = new Autogenerated.GetJobRequest { Name = jobName };
            var grpcCallOptions = DaprClientUtilities.ConfigureGrpcCallOptions(typeof(DaprJobsClient).Assembly, this.DaprApiToken, cancellationToken);
            var response = await _versionAwareClient.GetJobAsync(envelope, grpcCallOptions);
            return DeserializeJobResponse(response);
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
            //Ignore our own cancellation
        }
        catch (RpcException ex) when (ex.StatusCode == StatusCode.Cancelled && cancellationToken.IsCancellationRequested)
        {
            // Ignore a remote cancellation due to our own cancellation
        }
        catch (Exception ex)
        {
            throw new DaprException(
                "Get job operation failed: the Dapr endpoint indicated a failure. See InnerException for details.", ex);
        }

        throw new DaprException("Get job operation failed: the Dapr endpoint did not return the expected value.");
    }

    /// <summary>
    /// Testable method for performing job response deserialization.
    /// </summary>
    /// <remarks>
    /// This is exposed strictly for testing purposes.
    /// </remarks>
    /// <param name="response">The job response to deserialize.</param>
    /// <returns>The deserialized job response.</returns>
    internal static DaprJobDetails DeserializeJobResponse(Autogenerated.GetJobResponse response)
        => DeserializeJob(response.Job);

    /// <summary>
    /// Maps a <see cref="Autogenerated.Job"/> protobuf message to a <see cref="DaprJobDetails"/>.
    /// </summary>
    /// <remarks>
    /// Shared by <see cref="GetJobAsync"/> and <see cref="ListJobsAsync"/> so that both code paths
    /// surface the job <c>Name</c> and apply identical schedule, failure-policy, ttl, repeats, and
    /// payload mapping. Exposed for testing purposes.
    /// </remarks>
    /// <param name="job">The protobuf job message returned by the Dapr runtime.</param>
    /// <returns>The deserialized job details.</returns>
    internal static DaprJobDetails DeserializeJob(Autogenerated.Job job)
    {
        var schedule = DateTime.TryParse(job.DueTime, out var dueTime)
            ? DaprJobSchedule.FromDateTime(dueTime)
            : new DaprJobSchedule(job.Schedule);

        IFailurePolicyResponse? failurePolicyResponse = null;
        if (job.FailurePolicy?.PolicyCase is not null)
        {
            switch (job.FailurePolicy.PolicyCase)
            {
                case Autogenerated.JobFailurePolicy.PolicyOneofCase.Drop:
                    failurePolicyResponse = new ConfiguredDropFailurePolicy();
                    break;
                case Autogenerated.JobFailurePolicy.PolicyOneofCase.Constant:
                    failurePolicyResponse = new ConfiguredConstantFailurePolicy(
                        job.FailurePolicy.Constant.HasMaxRetries,
                        (int)job.FailurePolicy.Constant.MaxRetries,
                        job.FailurePolicy.Constant.Interval.ToTimeSpan());
                    break;
                case Autogenerated.JobFailurePolicy.PolicyOneofCase.None:
                default:
                    failurePolicyResponse = null;
                    break;
            }
        }

        return new DaprJobDetails(schedule)
        {
            Name = !string.IsNullOrWhiteSpace(job.Name) ? job.Name : null,
            DueTime = !string.IsNullOrWhiteSpace(job.DueTime) ? DateTime.Parse(job.DueTime) : null,
            Ttl = !string.IsNullOrWhiteSpace(job.Ttl) ? DateTime.Parse(job.Ttl) : null,
            RepeatCount = (int?)job.Repeats,
            Payload = job.Data?.Value?.ToByteArray() ?? null,
            FailurePolicy = failurePolicyResponse
        };
    }

    /// <summary>
    /// Deletes the specified job.
    /// </summary>
    /// <param name="jobName">The name of the job.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns></returns>
    public override async Task DeleteJobAsync(string jobName, CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(jobName))
        {
            throw new ArgumentNullException(nameof(jobName));
        }

        try
        {
            var envelope = new Autogenerated.DeleteJobRequest { Name = jobName };
            var grpcCallOptions = DaprClientUtilities.ConfigureGrpcCallOptions(typeof(DaprJobsClient).Assembly, this.DaprApiToken, cancellationToken);
            await _versionAwareClient.DeleteJobAsync(envelope, grpcCallOptions);
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
            //Ignore our own cancellation
        }
        catch (RpcException ex) when (ex.StatusCode == StatusCode.Cancelled && cancellationToken.IsCancellationRequested)
        {
            // Ignore a remote cancellation due to our own cancellation
        }
        catch (Exception ex)
        {
            throw new DaprException(
                "Delete job operation failed: the Dapr endpoint indicated a failure. See InnerException for details.",
                ex);
        }
    }

    /// <summary>
    /// Retrieves the list of all jobs registered for the current application ID.
    /// </summary>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>The list of registered jobs. The list is empty when no jobs are registered.</returns>
    public override async Task<IReadOnlyList<DaprJobDetails>> ListJobsAsync(CancellationToken cancellationToken = default)
    {
        try
        {
            var envelope = new Autogenerated.ListJobsRequest();
            var grpcCallOptions = DaprClientUtilities.ConfigureGrpcCallOptions(typeof(DaprJobsClient).Assembly, this.DaprApiToken, cancellationToken);
            var response = await _versionAwareClient.ListJobsAsync(envelope, grpcCallOptions);

            // The runtime may legitimately return an empty list; map each returned Job via the
            // shared deserializer so names, schedules, and failure policies are surfaced consistently
            // with GetJobAsync.
            var jobs = response.Jobs;
            if (jobs.Count == 0)
            {
                return Array.Empty<DaprJobDetails>();
            }

            var result = new List<DaprJobDetails>(jobs.Count);
            foreach (var job in jobs)
            {
                result.Add(DeserializeJob(job));
            }
            return result;
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
            //Ignore our own cancellation
        }
        catch (RpcException ex) when (ex.StatusCode == StatusCode.Cancelled && cancellationToken.IsCancellationRequested)
        {
            // Ignore a remote cancellation due to our own cancellation
        }
        catch (Exception ex)
        {
            throw new DaprException(
                "List jobs operation failed: the Dapr endpoint indicated a failure. See InnerException for details.",
                ex);
        }

        // A cancelled request that fell through the cancellation guards returns an empty list
        // rather than throwing, consistent with the list-operation contract.
        return Array.Empty<DaprJobDetails>();
    }

    /// <summary>
    /// Deletes every job whose name begins with the supplied <paramref name="namePrefix"/>.
    /// When <paramref name="namePrefix"/> is <c>null</c> or whitespace, all jobs associated with
    /// the current application ID are deleted (purge-all semantics).
    /// </summary>
    /// <param name="namePrefix">
    /// The case-sensitive prefix used to match job names. When <c>null</c> or whitespace,
    /// all jobs for the application ID are deleted.
    /// </param>
    /// <param name="cancellationToken">Cancellation token.</param>
    public override async Task DeleteJobsByPrefixAsync(string? namePrefix = null, CancellationToken cancellationToken = default)
    {
        try
        {
            var envelope = new Autogenerated.DeleteJobsByPrefixRequest();
            if (!string.IsNullOrWhiteSpace(namePrefix))
            {
                envelope.NamePrefix = namePrefix;
            }

            var grpcCallOptions = DaprClientUtilities.ConfigureGrpcCallOptions(typeof(DaprJobsClient).Assembly, this.DaprApiToken, cancellationToken);
            await _versionAwareClient.DeleteJobsByPrefixAsync(envelope, grpcCallOptions);
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
            //Ignore our own cancellation
        }
        catch (RpcException ex) when (ex.StatusCode == StatusCode.Cancelled && cancellationToken.IsCancellationRequested)
        {
            // Ignore a remote cancellation due to our own cancellation
        }
        catch (Exception ex)
        {
            throw new DaprException(
                "Delete jobs by prefix operation failed: the Dapr endpoint indicated a failure. See InnerException for details.",
                ex);
        }
    }

    /// <summary>
    /// Deletes every job associated with the current application ID. This is a convenience
    /// wrapper around <see cref="DeleteJobsByPrefixAsync"/> that passes a <c>null</c> prefix,
    /// which the Dapr runtime interprets as "delete all jobs for this app ID".
    /// </summary>
    /// <param name="cancellationToken">Cancellation token.</param>
    public override Task PurgeAllJobsAsync(CancellationToken cancellationToken = default)
        => DeleteJobsByPrefixAsync(namePrefix: null, cancellationToken);

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            this.HttpClient.Dispose();
        }
    }
}
