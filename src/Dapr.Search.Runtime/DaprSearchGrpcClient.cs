using System.Collections.ObjectModel;
using System.Text.Json;
using Dapr.Common;
using Dapr.Common.Serialization;
using Google.Protobuf;
using Google.Protobuf.Collections;
using Google.Protobuf.WellKnownTypes;
using Grpc.Core;
using Grpc.Net.Client;
using Autogenerated = Dapr.Client.Autogen.Grpc.v1;
using Enum = System.Enum;

namespace Dapr.Search;

internal sealed class DaprSearchGrpcClient(
    Autogenerated.Dapr.DaprClient client,
    HttpClient httpClient,
    JsonDaprSerializer serializer,
    string? daprApiToken = null,
    GrpcChannel? channel = null) : DaprSearchClient
{
    public override Task CreateIndexAsync(string storeName, string index,
        IReadOnlyDictionary<string, string>? metadata = null, CancellationToken cancellationToken = default)
    {
        ValidateIndex(storeName, index);
        var request = new Autogenerated.CreateIndexRequestAlpha1 { StoreName = storeName, Index = index };
        AddMetadata(request.Metadata, metadata);
        return InvokeAsync(options => client.CreateIndexAlpha1Async(request, options), cancellationToken);
    }

    public override async Task<SearchIndex> GetIndexAsync(string storeName, string index,
        IReadOnlyDictionary<string, string>? metadata = null, CancellationToken cancellationToken = default)
    {
        ValidateIndex(storeName, index);
        var request = new Autogenerated.GetIndexRequestAlpha1 { StoreName = storeName, Index = index };
        AddMetadata(request.Metadata, metadata);
        var response = await InvokeAsync(options => client.GetIndexAlpha1Async(request, options), cancellationToken)
            .ConfigureAwait(false);
        return new SearchIndex(response.Index, response.DocumentCount, Snapshot(response.Properties));
    }

    public override async Task<IReadOnlyList<string>> ListIndexesAsync(string storeName,
        IReadOnlyDictionary<string, string>? metadata = null, CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(storeName);
        var request = new Autogenerated.ListIndexesRequestAlpha1 { StoreName = storeName };
        AddMetadata(request.Metadata, metadata);
        var response = await InvokeAsync(options => client.ListIndexesAlpha1Async(request, options), cancellationToken)
            .ConfigureAwait(false);
        return response.Indexes.ToArray();
    }

    public override Task DeleteIndexAsync(string storeName, string index,
        IReadOnlyDictionary<string, string>? metadata = null, CancellationToken cancellationToken = default)
    {
        ValidateIndex(storeName, index);
        var request = new Autogenerated.DeleteIndexRequestAlpha1 { StoreName = storeName, Index = index };
        AddMetadata(request.Metadata, metadata);
        return InvokeAsync(options => client.DeleteIndexAlpha1Async(request, options), cancellationToken);
    }

    public override async Task<IndexDocumentsResult> IndexDocumentsAsync<T>(string storeName, string index,
        IReadOnlyList<SearchDocument<T>> documents, IndexingOptions? options = null,
        IReadOnlyDictionary<string, string>? metadata = null, CancellationToken cancellationToken = default)
    {
        ValidateIndex(storeName, index);
        ArgumentNullException.ThrowIfNull(documents);
        var request = new Autogenerated.IndexDocumentsRequestAlpha1
        {
            StoreName = storeName, Index = index, Options = ToGrpcOptions(options)
        };
        foreach (var document in documents)
        {
            ArgumentNullException.ThrowIfNull(document);
            ArgumentException.ThrowIfNullOrWhiteSpace(document.Id);
            var grpcDocument = new Autogenerated.SearchDocument
            {
                Id = document.Id, Content = ByteString.CopyFrom(serializer.SerializeToUtf8Bytes(document.Content))
            };
            AddMetadata(grpcDocument.Metadata, document.Metadata);
            request.Documents.Add(grpcDocument);
        }

        AddMetadata(request.Metadata, metadata);
        var response = await InvokeAsync(callOptions => client.IndexDocumentsAlpha1Async(request, callOptions),
                cancellationToken)
            .ConfigureAwait(false);
        var failures = response.FailedItems.Select(item =>
        {
            if (item.Error is null || item.Error.Code == 0)
                throw new DaprException("Search returned an item failure without a non-OK status.");
            return new SearchFailedItem(item.Id, item.Error.Code, item.Error.Message,
                item.Error.Details.Select(detail =>
                    new SearchErrorDetail(detail.TypeUrl, detail.Value.ToByteArray())).ToArray());
        }).ToArray();
        return new IndexDocumentsResult(ToAck(response.Ack), failures);
    }

    public override async Task<IReadOnlyList<SearchDocument<T>>> GetDocumentsAsync<T>(string storeName, string index,
        IReadOnlyList<string> ids, bool? includeContent = null,
        IReadOnlyDictionary<string, string>? metadata = null, CancellationToken cancellationToken = default)
    {
        ValidateIndex(storeName, index);
        var request = new Autogenerated.GetDocumentsRequestAlpha1 { StoreName = storeName, Index = index };
        AddIds(request.Ids, ids);
        if (includeContent.HasValue)
            request.IncludeContent = includeContent.Value;
        AddMetadata(request.Metadata, metadata);
        var response = await InvokeAsync(options => client.GetDocumentsAlpha1Async(request, options), cancellationToken)
            .ConfigureAwait(false);
        return response.Documents.Select(ToDocument<T>).ToArray();
    }

    public override async Task<IndexAck> DeleteDocumentsAsync(string storeName, string index,
        IReadOnlyList<string> ids, IndexingOptions? options = null,
        IReadOnlyDictionary<string, string>? metadata = null, CancellationToken cancellationToken = default)
    {
        ValidateIndex(storeName, index);
        var request = new Autogenerated.DeleteDocumentsRequestAlpha1
        {
            StoreName = storeName, Index = index, Options = ToGrpcOptions(options)
        };
        AddIds(request.Ids, ids);
        AddMetadata(request.Metadata, metadata);
        var response = await InvokeAsync(callOptions => client.DeleteDocumentsAlpha1Async(request, callOptions),
                cancellationToken)
            .ConfigureAwait(false);
        return ToAck(response.Ack);
    }

    public override async Task<SearchResult<T>> SearchAsync<T>(string storeName, string index,
        SearchQuery? query = null, IReadOnlyDictionary<string, string>? metadata = null,
        CancellationToken cancellationToken = default)
    {
        ValidateIndex(storeName, index);
        var request = new Autogenerated.SearchRequestAlpha1
        {
            StoreName = storeName, Index = index, Query = ToGrpcQuery(query)
        };
        AddMetadata(request.Metadata, metadata);
        var response = await InvokeAsync(options => client.SearchAlpha1Async(request, options), cancellationToken)
            .ConfigureAwait(false);
        return new SearchResult<T>(
            response.Hits.Select(hit => new SearchHit<T>(
                ToDocument<T>(hit.Document), hit.Score, Snapshot(hit.Highlights))).ToArray(),
            response.HasTotalHits ? response.TotalHits : null,
            (TotalHitsRelation)response.TotalHitsRelation,
            response.HasContinuationToken ? response.ContinuationToken : null);
    }

    private async Task<T> InvokeAsync<T>(Func<CallOptions, AsyncUnaryCall<T>> operation,
        CancellationToken cancellationToken)
    {
        ThrowIfDisposed();
        cancellationToken.ThrowIfCancellationRequested();
        var options = DaprClientUtilities.ConfigureGrpcCallOptions(typeof(DaprSearchClient).Assembly,
            daprApiToken, cancellationToken);
        try
        {
            using var call = operation(options);
            return await call.ResponseAsync.ConfigureAwait(false);
        }
        catch (RpcException ex) when (ex.StatusCode == StatusCode.Cancelled &&
                                      cancellationToken.IsCancellationRequested)
        {
            throw new OperationCanceledException("Search operation was canceled.", ex, cancellationToken);
        }
        catch (RpcException ex)
        {
            throw new DaprException(
                "Search operation failed: the Dapr endpoint indicated a failure. See InnerException for details.", ex);
        }
    }

    private SearchDocument<T> ToDocument<T>(Autogenerated.SearchDocument document)
    {
        if (document is null)
            throw new DaprException("Search returned a hit without a document.");
        return new SearchDocument<T>(document.Id,
            serializer.DeserializeFromUtf8Bytes<T>(document.Content.Span), Snapshot(document.Metadata));
    }

    private static void ValidateIndex(string storeName, string index)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(storeName);
        ArgumentException.ThrowIfNullOrWhiteSpace(index);
    }

    private static void AddIds(RepeatedField<string> target, IReadOnlyList<string> ids)
    {
        ArgumentNullException.ThrowIfNull(ids);
        foreach (var id in ids)
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(id);
            target.Add(id);
        }
    }

    private static void AddMetadata(MapField<string, string> target, IReadOnlyDictionary<string, string>? metadata)
    {
        if (metadata is not null)
            foreach (var (key, value) in metadata)
                target.Add(key, value);
    }

    private static IReadOnlyDictionary<string, string> Snapshot(MapField<string, string> source) =>
        new ReadOnlyDictionary<string, string>(new Dictionary<string, string>(source, StringComparer.Ordinal));

    private static IndexAck ToAck(Autogenerated.IndexAck ack) => ack switch
    {
        Autogenerated.IndexAck.Queued => IndexAck.Queued,
        Autogenerated.IndexAck.Completed => IndexAck.Completed,
        _ => throw new DaprException($"Search returned an invalid write acknowledgement: {ack}.")
    };

    private static Autogenerated.IndexingOptionsAlpha1? ToGrpcOptions(IndexingOptions? options)
    {
        if (options is null)
            return null;
        if (!Enum.IsDefined(options.Mode))
            throw new ArgumentOutOfRangeException(nameof(options), "Unknown indexing mode.");
        if (options.Mode == IndexingMode.WaitForCompletion)
        {
            if (options.WaitTimeout is null || options.WaitTimeout <= TimeSpan.Zero)
                throw new ArgumentException("WaitForCompletion requires a positive WaitTimeout.", nameof(options));
            if (options.OnWaitTimeout is null || !Enum.IsDefined(options.OnWaitTimeout.Value))
                throw new ArgumentException("WaitForCompletion requires an explicit OnWaitTimeout action.",
                    nameof(options));
        }
        else if (options.WaitTimeout is not null || options.OnWaitTimeout is not null)
        {
            throw new ArgumentException("WaitTimeout and OnWaitTimeout are only valid with WaitForCompletion.",
                nameof(options));
        }

        return new Autogenerated.IndexingOptionsAlpha1
        {
            Mode = (Autogenerated.IndexingMode)options.Mode,
            WaitTimeout = options.WaitTimeout is { } timeout ? Duration.FromTimeSpan(timeout) : null,
            OnWaitTimeout = options.OnWaitTimeout is { } action
                ? (Autogenerated.IndexingWaitTimeoutAction)action
                : Autogenerated.IndexingWaitTimeoutAction.Unspecified
        };
    }

    private static Autogenerated.SearchQuery? ToGrpcQuery(SearchQuery? query)
    {
        if (query is null)
            return null;
        if (query.Text is not null && query.Native is not null)
            throw new ArgumentException("Text and Native queries are mutually exclusive.", nameof(query));

        var result = new Autogenerated.SearchQuery();
        if (query.Text is not null)
            result.Text = query.Text;
        if (query.Native is { } native)
            result.Native = ToStruct(native, nameof(query.Native));
        if (query.Filter is { } filter)
            result.Filter = ToStruct(filter, nameof(query.Filter));
        if (query.TopK is { } topK)
            result.TopK = topK;
        if (query.ContinuationToken is { } token)
            result.ContinuationToken = token;
        if (query.IncludeContent is { } includeContent)
            result.IncludeContent = includeContent;
        AddIds(result.ReturnFields, query.ReturnFields);
        AddIds(result.SearchFields, query.SearchFields);
        AddIds(result.HighlightFields, query.HighlightFields);
        ArgumentNullException.ThrowIfNull(query.Sort);
        foreach (var sort in query.Sort)
        {
            ArgumentNullException.ThrowIfNull(sort);
            ArgumentException.ThrowIfNullOrWhiteSpace(sort.Field);
            if (!Enum.IsDefined(sort.Order))
                throw new ArgumentOutOfRangeException(nameof(query), "Unknown sort order.");
            result.Sort.Add(new Autogenerated.SortClause
            {
                Field = sort.Field, Order = (Autogenerated.SortOrder)sort.Order
            });
        }

        return result;
    }

    private static Struct ToStruct(JsonElement value, string parameterName)
    {
        if (value.ValueKind != JsonValueKind.Object)
            throw new ArgumentException("Expected a JSON object.", parameterName);
        return Struct.Parser.ParseJson(value.GetRawText());
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            channel?.Dispose();
            httpClient.Dispose();
        }
    }
}
