using Dapr.Common;
using Dapr.Common.Serialization;
using Microsoft.Extensions.Configuration;
using Autogenerated = Dapr.Client.Autogen.Grpc.v1;

namespace Dapr.Vector;

/// <summary>Builds a standalone Vector client using the standard Dapr endpoint, token and JSON options.</summary>
/// <param name="configuration">Optional configuration used to resolve Dapr defaults.</param>
public sealed class DaprVectorClientBuilder(IConfiguration? configuration = null)
    : DaprGenericClientBuilder<DaprVectorClient>(configuration)
{
    /// <inheritdoc />
    public override DaprVectorClient Build()
    {
        var deps = BuildDaprClientDependencies(typeof(DaprVectorClient).Assembly);
        return new DaprVectorGrpcClient(new Autogenerated.Dapr.DaprClient(deps.channel),
            deps.httpClient, new JsonDaprSerializer(JsonSerializerOptions), deps.daprApiToken, deps.channel);
    }
}
