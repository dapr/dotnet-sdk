    public override async Task<IReadOnlyList<VectorBatchQueryResult<T>>> BatchQueryVectorsAsync<T>(
        string storeName, string collection, IReadOnlyList<VectorQuery> queries,
        IReadOnlyDictionary<string, string>? metadata = null, CancellationToken cancellationToken = default)
    {
        ValidateCollection(storeName, collection);
        ArgumentNullException.ThrowIfNull(queries);
        var request =
            new Autogenerated.BatchQueryVectorsRequestAlpha1 { StoreName = storeName, Collection = collection };
        foreach (var query in queries)
            request.Queries.Add(ToGrpcQuery(query));
        AddMetadata(request.Metadata, metadata);
        var response = await InvokeAsync(options => client.BatchQueryVectorsAlpha1Async(request, options),
                cancellationToken)
            .ConfigureAwait(false);
        if (response.Results.Count != request.Queries.Count)
            throw new DaprException("Vector returned a batch result count that differs from the query count.");
        return response.Results.Select(result => result.ResultCase switch
        {
            Autogenerated.BatchQueryResultAlpha1.ResultOneofCase.Response =>
                new VectorBatchQueryResult<T>(ToResult<T>(result.Response)),
            Autogenerated.BatchQueryResultAlpha1.ResultOneofCase.Error =>
                new VectorBatchQueryResult<T>(ToError(result.Error)),
            _ => throw new DaprException("Vector returned a batch outcome without a response or error.")
        }).ToArray();
    }

    private VectorQueryResult<T> ToResult<T>(Autogenerated.QueryVectorsResponseAlpha1 response) =>
        new(response.Matches.Select(match => new VectorMatch<T>(ToRecord<T>(match.Record), match.Score)).ToArray(),
            ToMetric(response.Metric));

    private VectorRecord<T> ToRecord<T>(Autogenerated.VectorRecord record)
    {
        if (record is null)
            throw new DaprException("Vector returned a match without a record.");
        var payload = !record.HasPayload ? default :
            typeof(T) == typeof(byte[]) ? (T)(object)record.Payload.ToByteArray() :
            serializer.DeserializeFromUtf8Bytes<T>(record.Payload.Span);
        using var attributes = record.Metadata is null ? null : JsonDocument.Parse(record.Metadata.ToString());
        return new VectorRecord<T>(record.Id, record.Values.ToArray(), payload, attributes?.RootElement.Clone());
    }

    private static VectorQueryError ToError(Google.Rpc.Status? error)
    {
        if (error is null || error.Code == 0)
            throw new DaprException("Vector returned an error without a non-OK status.");
        return new VectorQueryError(error.Code, error.Message, error.Details.Select(detail =>
            new VectorErrorDetail(detail.TypeUrl, detail.Value.ToByteArray())).ToArray());
    }

    private static void ValidateCollection(string storeName, string collection)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(storeName);
        ArgumentException.ThrowIfNullOrWhiteSpace(collection);
    }

    private static void ValidateMetric(DistanceMetric metric)
    {
        if (!Enum.IsDefined(metric))
            throw new ArgumentOutOfRangeException(nameof(metric), "Unknown distance metric.");
    }

    private static DistanceMetric ToMetric(Autogenerated.DistanceMetric metric) => metric switch
    {
        Autogenerated.DistanceMetric.Cosine => DistanceMetric.Cosine,
        Autogenerated.DistanceMetric.DotProduct => DistanceMetric.DotProduct,
        Autogenerated.DistanceMetric.Euclidean => DistanceMetric.Euclidean,
        _ => throw new DaprException($"Vector returned an invalid effective metric: {metric}.")
    };

    private static IndexAck ToAck(Autogenerated.IndexAck ack) => ack switch
    {
        Autogenerated.IndexAck.Queued => IndexAck.Queued,
        Autogenerated.IndexAck.Completed => IndexAck.Completed,
        _ => throw new DaprException($"Vector returned an invalid write acknowledgement: {ack}.")
    };

    private static void AddIds(RepeatedField<string> target, IReadOnlyList<string> ids)
    {
        ArgumentNullException.ThrowIfNull(ids);
        foreach (var id in ids)
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(id);
            target.Add(id);
        }
    }

    private static void AddMetadata(MapField<string, string> target, IReadOnlyDictionary<string, string>? metadata)
    {
        if (metadata is not null)
            foreach (var (key, value) in metadata)
                target.Add(key, value);
    }

    private static Struct ToStruct(JsonElement value, string parameterName)
    {
        if (value.ValueKind != JsonValueKind.Object)
            throw new ArgumentException("Expected a JSON object.", parameterName);
        return Struct.Parser.ParseJson(value.GetRawText());
    }

    private static Autogenerated.VectorQuery ToGrpcQuery(VectorQuery query)
    {
        ArgumentNullException.ThrowIfNull(query);
        if ((query.Vector is null) == (query.ById is null))
            throw new ArgumentException("Exactly one of Vector and ById is required.", nameof(query));
        ValidateMetric(query.Metric);
        var result = new Autogenerated.VectorQuery { Metric = (Autogenerated.DistanceMetric)query.Metric };
        if (query.Vector is { } vector)
        {
            if (vector.Count == 0)
                throw new ArgumentException("The query vector must not be empty.", nameof(query));
            result.Vector = new Autogenerated.VectorRecord();
            result.Vector.Values.Add(vector);
        }
        else
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(query.ById);
            result.ById = query.ById;
        }

        if (query.TopK is { } topK)
            result.TopK = topK;
        if (query.Filter is { } filter)
            result.Filter = ToStruct(filter, nameof(query.Filter));
        if (query.IncludeValues is { } values)
            result.IncludeValues = values;
        if (query.IncludePayload is { } payload)
            result.IncludePayload = payload;
        if (query.ScoreThreshold is { } threshold)
            result.ScoreThreshold = threshold;
        return result;
    }

    private static Autogenerated.IndexingOptionsAlpha1? ToGrpcOptions(IndexingOptions? options)
    {
        if (options is null)
            return null;
        if (!Enum.IsDefined(options.Mode))
            throw new ArgumentOutOfRangeException(nameof(options), "Unknown indexing mode.");
        if (options.Mode == IndexingMode.WaitForCompletion)
        {
            if (options.WaitTimeout is null || options.WaitTimeout <= TimeSpan.Zero)
                throw new ArgumentException("WaitForCompletion requires a positive WaitTimeout.", nameof(options));
            if (options.OnWaitTimeout is null || !Enum.IsDefined(options.OnWaitTimeout.Value))
                throw new ArgumentException("WaitForCompletion requires an explicit OnWaitTimeout action.",
                    nameof(options));
        }
        else if (options.WaitTimeout is not null || options.OnWaitTimeout is not null)
            throw new ArgumentException("WaitTimeout and OnWaitTimeout are only valid with WaitForCompletion.",
                nameof(options));

        return new Autogenerated.IndexingOptionsAlpha1
        {
            Mode = (Autogenerated.IndexingMode)options.Mode,
            WaitTimeout = options.WaitTimeout is { } timeout ? Duration.FromTimeSpan(timeout) : null,
            OnWaitTimeout = options.OnWaitTimeout is { } action
                ? (Autogenerated.IndexingWaitTimeoutAction)action
                : Autogenerated.IndexingWaitTimeoutAction.Unspecified
        };
    }

    private async Task<T> InvokeAsync<T>(Func<CallOptions, AsyncUnaryCall<T>> operation,
        CancellationToken cancellationToken)
    {
        ThrowIfDisposed();
        cancellationToken.ThrowIfCancellationRequested();
        var options =
            DaprClientUtilities.ConfigureGrpcCallOptions(typeof(DaprVectorClient).Assembly, daprApiToken,
                cancellationToken);
        try
        {
            using var call = operation(options);
            return await call.ResponseAsync.ConfigureAwait(false);
        }
        catch (RpcException ex) when (ex.StatusCode == StatusCode.Cancelled &&
                                      cancellationToken.IsCancellationRequested)
        {
            throw new OperationCanceledException("Vector operation was canceled.", ex, cancellationToken);
        }
        catch (RpcException ex)
        {
            throw new DaprException(
                "Vector operation failed: the Dapr endpoint indicated a failure. See InnerException for details.", ex);
        }
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            channel?.Dispose();
            httpClient.Dispose();
        }
    }
