    public override async Task<UpsertVectorsResult> UpsertVectorsAsync<T>(string storeName, string collection,
        IReadOnlyList<VectorRecord<T>> records, IndexingOptions? options = null,
        IReadOnlyDictionary<string, string>? metadata = null, CancellationToken cancellationToken = default)
    {
        ValidateCollection(storeName, collection);
        ArgumentNullException.ThrowIfNull(records);
        var request = new Autogenerated.UpsertVectorsRequestAlpha1
        {
            StoreName = storeName, Collection = collection, Options = ToGrpcOptions(options)
        };
        foreach (var record in records)
        {
            ArgumentNullException.ThrowIfNull(record);
            ArgumentException.ThrowIfNullOrWhiteSpace(record.Id);
            ArgumentNullException.ThrowIfNull(record.Values);
            var item = new Autogenerated.VectorRecord { Id = record.Id };
            // The provider validates dimensions and values per item, preserving partial success.
            item.Values.Add(record.Values);
            if (record.Payload is not null)
                item.Payload = typeof(T) == typeof(byte[])
                    ? ByteString.CopyFrom((byte[])(object)record.Payload)
                    : ByteString.CopyFrom(serializer.SerializeToUtf8Bytes(record.Payload));
            if (record.Metadata is { } attributes)
                item.Metadata = ToStruct(attributes, nameof(record.Metadata));
            request.Records.Add(item);
        }

        AddMetadata(request.Metadata, metadata);
        var response = await InvokeAsync(callOptions => client.UpsertVectorsAlpha1Async(request, callOptions),
                cancellationToken)
            .ConfigureAwait(false);
        return new UpsertVectorsResult(ToAck(response.Ack), response.FailedItems.Select(item =>
        {
            var error = ToError(item.Error);
            return new VectorFailedItem(item.Id, error.Code, error.Message, error.Details);
        }).ToArray());
    }

    public override async Task<IReadOnlyList<VectorRecord<T>>> GetVectorsAsync<T>(string storeName, string collection,
