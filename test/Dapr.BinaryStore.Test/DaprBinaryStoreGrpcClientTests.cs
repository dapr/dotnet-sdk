    }

    [Theory]
    [InlineData(StatusCode.ResourceExhausted, 0)]
    [InlineData(StatusCode.ResourceExhausted, 1)]
    [InlineData(StatusCode.ResourceExhausted, 2)]
    [InlineData(StatusCode.AlreadyExists, 0)]
    [InlineData(StatusCode.AlreadyExists, 1)]
    [InlineData(StatusCode.AlreadyExists, 2)]
    public async Task SetBinaryFile_TransportCancellation_PreservesServerRejection(StatusCode statusCode, int failureStage)
    {
        var serverError = new RpcException(new Status(statusCode, "Upload rejected"));
        var cancellation = new OperationCanceledException();
        var invoker = new FakeCallInvoker
        {
            ResponseError = serverError,
            WriteError = failureStage < 2 ? cancellation : null,
            SuccessfulWritesBeforeError = failureStage,
            CompleteError = failureStage == 2 ? cancellation : null
        };
        using var client = CreateClient(invoker);
        using var source = new MemoryStream([1]);

        var error = await Assert.ThrowsAsync<DaprException>(() =>
            client.SetBinaryFileAsync("s", "f", source, cancellationToken: TestContext.Current.CancellationToken));

        Assert.Same(serverError, error.InnerException);
        Assert.Equal(statusCode, Assert.IsType<RpcException>(error.InnerException).StatusCode);
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public async Task SetBinaryFile_CallerCancellationDuringWrite_IsNotReplacedByServerError(bool rpcCancellation)
    {
        using var cts = new CancellationTokenSource();
        var invoker = new FakeCallInvoker
        {
            ResponseError = new RpcException(new Status(StatusCode.AlreadyExists, "Upload rejected")),
            WriteError = rpcCancellation
                ? new RpcException(new Status(StatusCode.Cancelled, "Cancelled"))
                : new OperationCanceledException(cts.Token),
            SuccessfulWritesBeforeError = 1,
            OnWriteFailure = cts.Cancel
        };
        using var client = CreateClient(invoker);
        using var source = new MemoryStream([1]);

        var error = await Assert.ThrowsAnyAsync<OperationCanceledException>(() =>
            client.SetBinaryFileAsync("s", "f", source, cancellationToken: cts.Token));

        Assert.Equal(cts.Token, error.CancellationToken);
    }

