    [Fact]
    public async Task SetBinaryFile_SendsInitialRequestThenSequencedChunks()
    {
        var invoker = new FakeCallInvoker();
        using var client = CreateClient(invoker);
        var data = Enumerable.Range(0, 10).Select(i => (byte)i).ToArray();

        await client.SetBinaryFileAsync("store", "dir/file.bin", new MemoryStream(data), overwrite: true, chunkSize: 4,
            cancellationToken: TestContext.Current.CancellationToken);

        Assert.True(invoker.CompleteCalled);
        Assert.Equal(4, invoker.Written.Count);

        var initial = invoker.Written[0].InitialRequest;
        Assert.Equal("store", initial.ComponentName);
        Assert.Equal("dir/file.bin", initial.FileName);
        Assert.True(initial.Overwrite);

        var payloads = invoker.Written.Skip(1).Select(w => w.Payload).ToList();
        Assert.Equal([0UL, 1UL, 2UL], payloads.Select(p => p.Seq));
        Assert.Equal(data, payloads.SelectMany(p => p.Data.ToByteArray()));
    }

    [Fact]
    public async Task SetBinaryFile_EmptyContent_SendsOnlyInitialRequest()
    {
        var invoker = new FakeCallInvoker();
        using var client = CreateClient(invoker);

        await client.SetBinaryFileAsync("store", "f", Stream.Null, cancellationToken: TestContext.Current.CancellationToken);

        Assert.Single(invoker.Written);
        Assert.True(invoker.CompleteCalled);
    }

    [Fact]
    public async Task SetBinaryFile_PooledBuffersPreserveChunkLimitAndPreviouslySentBytes()
    {
        var invoker = new FakeCallInvoker();
        using var client = CreateClient(invoker);
        var data = Enumerable.Range(0, 103).Select(i => (byte)i).ToArray();
        await client.SetBinaryFileAsync("store", "first", new MemoryStream(data), chunkSize: 17,
            cancellationToken: TestContext.Current.CancellationToken);
        var firstPayloads = invoker.Written.Skip(1).Select(message => message.Payload).ToArray();
        Assert.All(firstPayloads, payload => Assert.InRange(payload.Data.Length, 1, 17));
        await client.SetBinaryFileAsync("store", "second", new MemoryStream(new byte[103]), chunkSize: 17,
            cancellationToken: TestContext.Current.CancellationToken);
        Assert.Equal(data, firstPayloads.SelectMany(payload => payload.Data.ToByteArray()));
    }

    [Fact]
    public async Task SetBinaryFile_ServerError_IsWrappedInDaprException()
