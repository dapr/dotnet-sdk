    private sealed class FakeCallInvoker : CallInvoker
    {
        public List<Autogenerated.SetBinaryFileRequestAlpha1> Written { get; } = [];
        public bool CompleteCalled { get; private set; }
        public Exception? ResponseError { get; init; }
        public Exception? WriteError { get; init; }
        public int SuccessfulWritesBeforeError { get; init; }
        public Action? OnWriteFailure { get; init; }
        public Exception? CompleteError { get; init; }
        public List<byte[]> DownloadChunks { get; init; } = [];
        public Exception? DownloadError { get; init; }
        public Autogenerated.DeleteBinaryFileRequestAlpha1? Deleted { get; private set; }

        public override AsyncClientStreamingCall<TRequest, TResponse> AsyncClientStreamingCall<TRequest, TResponse>(
            Method<TRequest, TResponse> method, string? host, CallOptions options)
        {
            var stream = new FakeRequestStream<TRequest>(this);
            Task<TResponse> response = ResponseError is null
                ? Task.FromResult(Activator.CreateInstance<TResponse>())
                : Task.FromException<TResponse>(ResponseError);
            return new AsyncClientStreamingCall<TRequest, TResponse>(
                stream, response, Task.FromResult(new Metadata()), () => Status.DefaultSuccess, () => [], () => { });
        }

        public override AsyncServerStreamingCall<TResponse> AsyncServerStreamingCall<TRequest, TResponse>(
            Method<TRequest, TResponse> method, string? host, CallOptions options, TRequest request)
        {
            var items = DownloadChunks
                .Select(c => (TResponse)(object)new Autogenerated.GetBinaryFileResponseAlpha1
                {
                    Payload = new Autogenerated.StreamPayload { Data = ByteString.CopyFrom(c) }
                }).ToList();
            return new AsyncServerStreamingCall<TResponse>(
                new FakeResponseStream<TResponse>(items, DownloadError), Task.FromResult(new Metadata()),
                () => Status.DefaultSuccess, () => [], () => { });
        }

        public override AsyncUnaryCall<TResponse> AsyncUnaryCall<TRequest, TResponse>(
            Method<TRequest, TResponse> method, string? host, CallOptions options, TRequest request)
        {
            Deleted = request as Autogenerated.DeleteBinaryFileRequestAlpha1;
            return new AsyncUnaryCall<TResponse>(
                Task.FromResult(Activator.CreateInstance<TResponse>()),
                Task.FromResult(new Metadata()), () => Status.DefaultSuccess, () => [], () => { });
        }

        public override TResponse BlockingUnaryCall<TRequest, TResponse>(
            Method<TRequest, TResponse> method, string? host, CallOptions options, TRequest request) =>
            throw new NotSupportedException();

        public override AsyncDuplexStreamingCall<TRequest, TResponse> AsyncDuplexStreamingCall<TRequest, TResponse>(
            Method<TRequest, TResponse> method, string? host, CallOptions options) =>
            throw new NotSupportedException();

        private sealed class FakeRequestStream<T>(FakeCallInvoker owner) : IClientStreamWriter<T>
        {
            public WriteOptions? WriteOptions { get; set; }

            public Task WriteAsync(T message)
            {
                if (owner.WriteError is not null && owner.Written.Count == owner.SuccessfulWritesBeforeError)
                {
                    owner.OnWriteFailure?.Invoke();
                    return Task.FromException(owner.WriteError);
                }

                owner.Written.Add((Autogenerated.SetBinaryFileRequestAlpha1)(object)message!);
                return Task.CompletedTask;
            }

            public Task WriteAsync(T message, CancellationToken cancellationToken)
            {
                cancellationToken.ThrowIfCancellationRequested();
                return WriteAsync(message);
            }

            public Task CompleteAsync()
            {
                owner.CompleteCalled = true;
                return owner.CompleteError is null ? Task.CompletedTask : Task.FromException(owner.CompleteError);
            }
        }

        private sealed class FakeResponseStream<T>(List<T> items, Exception? error) : IAsyncStreamReader<T>
        {
            private int _index = -1;
            public T Current => items[_index];

            public Task<bool> MoveNext(CancellationToken cancellationToken)
            {
                _index++;
                if (_index < items.Count)
                    return Task.FromResult(true);
                return error is null ? Task.FromResult(false) : Task.FromException<bool>(error);
            }
        }
    }

    private static DaprBinaryStoreGrpcClient CreateClient(CallInvoker? invoker = null) =>
        new(new Autogenerated.Dapr.DaprClient(invoker ?? new FakeCallInvoker()), new HttpClient());

