    [Fact]
    public async Task StartWorkflowAsync_WhenDiscoveryIsUnknownAndBetaIsUnavailable_FallsBackToAlpha()
    {
        var cancellationToken = TestContext.Current.CancellationToken;
        var capabilities = CreateCapabilities(DaprRuntimeSupport.Unknown);
        var inner = new Mock<Autogenerated.Dapr.DaprClient>(MockBehavior.Strict);

        inner
            .Setup(client => client.StartWorkflowBeta1Async(
                It.IsAny<Autogenerated.StartWorkflowRequest>(),
                It.IsAny<CallOptions>()))
            .Throws(new RpcException(new Status(StatusCode.Unimplemented, "Beta method unavailable.")));

#pragma warning disable CS0612 // The generated selector intentionally invokes the obsolete runtime fallback.
        inner
            .Setup(client => client.StartWorkflowAlpha1Async(
                It.IsAny<Autogenerated.StartWorkflowRequest>(),
                It.IsAny<CallOptions>()))
            .Returns(CreateUnaryCall<Autogenerated.StartWorkflowResponse>());
#pragma warning restore CS0612

        var client = new VersionAwareDaprClient(inner.Object, capabilities.Object);

        var firstResponse = await client.StartWorkflowAsync(
            new Autogenerated.StartWorkflowRequest(),
            new CallOptions(cancellationToken: cancellationToken));
        var secondResponse = await client.StartWorkflowAsync(
            new Autogenerated.StartWorkflowRequest(),
            new CallOptions(cancellationToken: cancellationToken));

        Assert.NotNull(firstResponse);
        Assert.NotNull(secondResponse);
        capabilities.Verify(capability => capability.GetMethodSupportAsync(
            "dapr.proto.runtime.v1.Dapr/StartWorkflowBeta1",
            cancellationToken), Times.Once);
        capabilities.Verify(capability => capability.GetMethodSupportAsync(
            "dapr.proto.runtime.v1.Dapr/StartWorkflowAlpha1",
            cancellationToken), Times.Once);
        inner.Verify(client => client.StartWorkflowBeta1Async(
            It.IsAny<Autogenerated.StartWorkflowRequest>(),
            It.IsAny<CallOptions>()), Times.Once);
#pragma warning disable CS0612 // Verify that the cached obsolete fallback is invoked directly.
        inner.Verify(client => client.StartWorkflowAlpha1Async(
            It.IsAny<Autogenerated.StartWorkflowRequest>(),
            It.IsAny<CallOptions>()), Times.Exactly(2));
#pragma warning restore CS0612
    }

