    [Fact]
    public async Task ConverseAsync_WhenDiscoveryIsUnknownAndAlpha2IsUnavailable_DoesNotGuessIncompatibleAlpha1()
    {
        var cancellationToken = TestContext.Current.CancellationToken;
        var capabilities = CreateCapabilities(DaprRuntimeSupport.Unknown);
        var inner = new Mock<Autogenerated.Dapr.DaprClient>(MockBehavior.Strict);
        inner
            .Setup(client => client.ConverseAlpha2Async(
                It.IsAny<Autogenerated.ConversationRequestAlpha2>(),
                It.IsAny<CallOptions>()))
            .Throws(new RpcException(new Status(StatusCode.Unimplemented, "Alpha2 method unavailable.")));

        var client = new VersionAwareDaprClient(inner.Object, capabilities.Object);

        var exception = await Assert.ThrowsAsync<NotSupportedException>(() => client.ConverseAsync(
            new Autogenerated.ConversationRequestAlpha2(),
            new CallOptions(cancellationToken: cancellationToken)));

        Assert.Contains("runtime method discovery is unavailable", exception.Message);
        Assert.Contains("ConverseAlpha1", exception.Message);
#pragma warning disable CS0612 // Verify that the obsolete incompatible fallback was not invoked.
        inner.Verify(client => client.ConverseAlpha1Async(
            It.IsAny<Autogenerated.ConversationRequest>(),
            It.IsAny<CallOptions>()), Times.Never);
#pragma warning restore CS0612
    }

    private static Mock<IDaprRuntimeCapabilities> CreateCapabilities(DaprRuntimeSupport support)
    {
        var capabilities = new Mock<IDaprRuntimeCapabilities>(MockBehavior.Strict);
        capabilities
            .Setup(capability => capability.GetMethodSupportAsync(
                It.IsAny<string>(),
                It.IsAny<CancellationToken>()))
            .ReturnsAsync(support);
        return capabilities;
    }

    private static AsyncUnaryCall<TResponse> CreateUnaryCall<TResponse>()
        where TResponse : new()
    {
        return new AsyncUnaryCall<TResponse>(
            Task.FromResult(new TResponse()),
            Task.FromResult(new Metadata()),
            () => Status.DefaultSuccess,
            () => new Metadata(),
            () => { });
    }
