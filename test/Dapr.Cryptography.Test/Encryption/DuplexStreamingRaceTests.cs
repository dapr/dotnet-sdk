    [Theory]
    [InlineData(true, true)]
    [InlineData(true, false)]
    [InlineData(false, true)]
    [InlineData(false, false)]
    public async Task ResponseCompletion_DoesNotHidePendingWriteFailure(bool encrypt, bool buffered)
    {
        using var fixture = new StreamingFixture(encrypt);
        var writeStarted = NewSignal();
        var responseFinished = NewSignal();
        var write = NewSignal();
        fixture.WriteAsync = async token =>
        {
            writeStarted.SetResult();
            await write.Task.WaitAsync(token);
        };
        fixture.MoveNextAsync = _ =>
        {
            responseFinished.SetResult();
            return Task.FromResult(false);
        };

        using var input = new MemoryStream(new byte[] { 1, 2, 3 });
        var operation = fixture.ProcessAsync(input, buffered);
        await writeStarted.Task.WaitAsync(fixture.Token);
        await responseFinished.Task.WaitAsync(fixture.Token);
        var completedBeforeWrite = operation.IsCompleted;
        var expected = new IOException("Delayed request write failure");
        write.SetException(expected);

        var actual = await Assert.ThrowsAsync<IOException>(() => operation.WaitAsync(fixture.Token));
        Assert.Same(expected, actual);
        Assert.False(completedBeforeWrite);
        Assert.Equal(buffered, input.CanRead);
        Assert.True(fixture.CallDisposed);
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public async Task ResponseCompletion_WaitsForRequestCompletionAndSurfacesFailure(bool encrypt)
    {
        using var fixture = new StreamingFixture(encrypt);
        var completionStarted = NewSignal();
        var completion = NewSignal();
        var responseFinished = NewSignal();
        fixture.CompleteAsync = () =>
        {
            completionStarted.SetResult();
            return completion.Task;
        };
        fixture.MoveNextAsync = _ =>
        {
            responseFinished.SetResult();
            return Task.FromResult(false);
        };

        using var input = new MemoryStream();
        var operation = fixture.ProcessAsync(input);
        await completionStarted.Task.WaitAsync(fixture.Token);
        await responseFinished.Task.WaitAsync(fixture.Token);
        var completedBeforeRequest = operation.IsCompleted;
        var expected = new IOException("Request completion failure");
        completion.SetException(expected);

        var actual = await Assert.ThrowsAsync<IOException>(() => operation.WaitAsync(fixture.Token));
        Assert.Same(expected, actual);
        Assert.False(completedBeforeRequest);
    }

    [Theory]
    [InlineData(true, true)]
    [InlineData(true, false)]
    [InlineData(false, true)]
    [InlineData(false, false)]
    public async Task ResponseFailure_CancelsAndJoinsPendingWriter(bool encrypt, bool buffered)
    {
        using var fixture = new StreamingFixture(encrypt);
        var writeStarted = NewSignal();
        var writeStopped = NewSignal();
        fixture.WriteAsync = async token =>
        {
            writeStarted.SetResult();
            try
            {
                await Task.Delay(Timeout.InfiniteTimeSpan, token);
            }
            finally
            {
                writeStopped.SetResult();
            }
        };
        var expected = new RpcException(new Status(StatusCode.Internal, "Response failure"));
        fixture.MoveNextAsync = async token =>
        {
            await writeStarted.Task.WaitAsync(token);
            throw expected;
        };

        using var input = new MemoryStream(new byte[] { 1, 2, 3 });
        var actual = await Assert.ThrowsAsync<RpcException>(
            () => fixture.ProcessAsync(input, buffered).WaitAsync(fixture.Token));

        Assert.Same(expected, actual);
        Assert.True(writeStopped.Task.IsCompletedSuccessfully);
        Assert.Equal(buffered, input.CanRead);
        Assert.True(fixture.CallDisposed);
    }

    [Theory]
