    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public async Task EarlyEnumerationExit_CancelsAndJoinsBothHalves(bool encrypt)
    {
        using var fixture = new StreamingFixture(encrypt);
        var writeStarted = NewSignal();
        var writeStopped = NewSignal();
        fixture.WriteAsync = async token =>
        {
            writeStarted.SetResult();
            try
            {
                await Task.Delay(Timeout.InfiniteTimeSpan, token);
            }
            finally
            {
                writeStopped.SetResult();
            }
        };
        var responseStopped = NewSignal();
        var responseCount = 0;
        fixture.MoveNextAsync = async token =>
        {
            await writeStarted.Task.WaitAsync(token);
            if (responseCount++ == 0)
            {
                return true;
            }

            try
            {
                await Task.Delay(Timeout.InfiniteTimeSpan, token);
                return false;
            }
            finally
            {
                responseStopped.SetResult();
            }
        };

        using var input = new MemoryStream(new byte[] { 1, 2, 3 });
        var enumerator = fixture.ProcessStream(input).GetAsyncEnumerator(fixture.Token);
        try
        {
            Assert.True(await enumerator.MoveNextAsync().AsTask().WaitAsync(fixture.Token));
            Assert.Equal(new byte[] { 9, 8, 7 }, enumerator.Current.ToArray());
        }
        finally
        {
            await enumerator.DisposeAsync().AsTask().WaitAsync(fixture.Token);
        }

        Assert.True(writeStopped.Task.IsCompletedSuccessfully);
        Assert.True(responseStopped.Task.IsCompletedSuccessfully);
        Assert.False(input.CanRead);
        Assert.True(fixture.CallDisposed);
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public async Task Cancellation_InterruptsRequestCompletion(bool encrypt)
    {
        using var fixture = new StreamingFixture(encrypt);
        var completionStarted = NewSignal();
        var completion = NewSignal();
        fixture.CompleteAsync = () =>
        {
            completionStarted.SetResult();
            return completion.Task;
        };
        fixture.OnCallDisposed = () => completion.TrySetCanceled();
        using var input = new MemoryStream();
        var operation = fixture.ProcessAsync(input);
        await completionStarted.Task.WaitAsync(fixture.Token);

        fixture.Cancel();

        await Assert.ThrowsAnyAsync<OperationCanceledException>(
            () => operation.WaitAsync(TimeSpan.FromSeconds(5), TestContext.Current.CancellationToken));
        Assert.True(fixture.CallDisposed);
        Assert.True(completion.Task.IsCompleted);
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public async Task PreCanceledOperation_ThrowsInsteadOfHanging(bool encrypt)
    {
        using var fixture = new StreamingFixture(encrypt);
        fixture.Cancel();
        using var input = new MemoryStream(new byte[] { 1, 2, 3 });

        await Assert.ThrowsAnyAsync<OperationCanceledException>(() =>
            fixture.ProcessAsync(input).WaitAsync(TimeSpan.FromSeconds(5), TestContext.Current.CancellationToken));
        Assert.True(fixture.CallDisposed);
    }

    private static TaskCompletionSource NewSignal() => new(TaskCreationOptions.RunContinuationsAsynchronously);

    private sealed class FailingReadStream(IOException exception) : MemoryStream
    {
        public override ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default)
            => ValueTask.FromException<int>(exception);
    }

    private sealed class StreamingFixture : IDisposable
    {
        private readonly bool encrypt;
        private readonly DaprEncryptionGrpcClient client;
        private readonly HttpClient httpClient = new();
        private readonly CancellationTokenSource cancellation =
            CancellationTokenSource.CreateLinkedTokenSource(TestContext.Current.CancellationToken);

        public Func<CancellationToken, Task> WriteAsync { get; set; } = _ => Task.CompletedTask;
        public Func<Task> CompleteAsync { get; set; } = () => Task.CompletedTask;
        public Func<CancellationToken, Task<bool>> MoveNextAsync { get; set; } = _ => Task.FromResult(false);
        public Action? OnCallDisposed { get; set; }
        public bool CallDisposed { get; private set; }
        public CancellationToken Token => cancellation.Token;

        public StreamingFixture(bool encrypt)
        {
            this.encrypt = encrypt;
            cancellation.CancelAfter(TimeSpan.FromSeconds(10));
            var dapr = new Mock<Autogenerated.Dapr.DaprClient>();
            dapr.Setup(x => x.EncryptAlpha1(It.IsAny<CallOptions>())).Returns(() =>
                CreateCall<Autogenerated.EncryptRequest, Autogenerated.EncryptResponse>(
                    new Autogenerated.EncryptResponse
                    {
                        Payload = new Autogenerated.StreamPayload { Data = ByteString.CopyFrom(9, 8, 7) }
                    }));
            dapr.Setup(x => x.DecryptAlpha1(It.IsAny<CallOptions>())).Returns(() =>
                CreateCall<Autogenerated.DecryptRequest, Autogenerated.DecryptResponse>(
                    new Autogenerated.DecryptResponse
                    {
                        Payload = new Autogenerated.StreamPayload { Data = ByteString.CopyFrom(9, 8, 7) }
                    }));
            client = new DaprEncryptionGrpcClient(dapr.Object, httpClient,
                new Mock<IDaprRuntimeCapabilities>().Object);
        }

        private AsyncDuplexStreamingCall<TRequest, TResponse> CreateCall<TRequest, TResponse>(TResponse response)
        {
            var writer = new Mock<IClientStreamWriter<TRequest>>();
            writer.Setup(x => x.WriteAsync(It.IsAny<TRequest>(), It.IsAny<CancellationToken>()))
                .Returns<TRequest, CancellationToken>((_, token) => WriteAsync(token));
            writer.Setup(x => x.CompleteAsync()).Returns(() => CompleteAsync());
            var reader = new Mock<IAsyncStreamReader<TResponse>>();
            reader.Setup(x => x.MoveNext(It.IsAny<CancellationToken>()))
                .Returns<CancellationToken>(token => MoveNextAsync(token));
            reader.Setup(x => x.Current).Returns(response);
            return new AsyncDuplexStreamingCall<TRequest, TResponse>(writer.Object, reader.Object,
                Task.FromResult(new Metadata()), () => Status.DefaultSuccess, () => new Metadata(), () =>
                {
                    CallDisposed = true;
                    OnCallDisposed?.Invoke();
                });
        }

        public IAsyncEnumerable<ReadOnlyMemory<byte>> ProcessStream(Stream input) => encrypt
            ? client.EncryptAsync("vault", input, "key", new EncryptionOptions(KeyWrapAlgorithm.Rsa), Token)
            : client.DecryptAsync("vault", input, "key", cancellationToken: Token);

        public async Task ProcessAsync(MemoryStream input, bool buffered = false)
        {
            if (buffered)
            {
                var bytes = new ReadOnlyMemory<byte>(input.ToArray());
                if (encrypt)
                {
                    await client.EncryptAsync("vault", bytes, "key", new EncryptionOptions(KeyWrapAlgorithm.Rsa), Token);
                }
                else
                {
                    await client.DecryptAsync("vault", bytes, "key", cancellationToken: Token);
                }
            }
            else
            {
                await foreach (var _ in ProcessStream(input)) { }
            }
        }

        public void Cancel() => cancellation.Cancel();

        public void Dispose()
        {
            cancellation.Dispose();
            client.Dispose();
            httpClient.Dispose();
        }
    }
}
