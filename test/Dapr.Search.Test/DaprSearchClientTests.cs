    [Fact]
    public async Task SearchMapsAllPortableOptionsAndResults()
    {
        var response = new Autogenerated.SearchResponseAlpha1
        {
            TotalHits = ulong.MaxValue,
            TotalHitsRelation = Autogenerated.TotalHitsRelation.LowerBound,
            ContinuationToken = "next",
            Hits =
            {
                new Autogenerated.SearchHit
                {
                    Document = new Autogenerated.SearchDocument
                    {
                        Id = "1", Content = ByteString.CopyFromUtf8("""{"title":"Dapr"}""")
                    },
                    Score = .75,
                    Highlights = { { "title", "<em>Dapr</em>" } }
                }
            }
        };
        var invoker = new SearchCallInvoker { Response = response };
        using var client = CreateClient(invoker);
        var query = new SearchQuery
        {
            Text = "Dapr",
            Filter =
                JsonSerializer.SerializeToElement(new
                {
                    title = new Dictionary<string, string> { ["$eq"] = "Dapr" }
                }),
            TopK = 10,
            ContinuationToken = "previous",
            IncludeContent = true,
            ReturnFields = ["title"],
            SearchFields = ["title"],
            HighlightFields = ["title"],
            Sort = [new SortClause("title", SortOrder.Descending)]
        };
        var result = await client.SearchAsync<Book>("store", "books", query, Metadata, Ct);
        var request = Assert.IsType<Autogenerated.SearchRequestAlpha1>(invoker.Request);
        Assert.Equal(("store", "books", "value"), (request.StoreName, request.Index, request.Metadata["setting"]));
        Assert.Equal("/dapr.proto.runtime.v1.Dapr/SearchAlpha1", invoker.Method);
        var wire = request.Query;
        Assert.Equal(Autogenerated.SearchQuery.KindOneofCase.Text, wire.KindCase);
        Assert.Equal("Dapr", wire.Text);
        Assert.Equal("Dapr", wire.Filter.Fields["title"].StructValue.Fields["$eq"].StringValue);
        Assert.Equal(10U, wire.TopK);
        Assert.True(wire.IncludeContent);
        Assert.Equal("previous", wire.ContinuationToken);
        Assert.Equal(["title"], wire.ReturnFields);
        Assert.Equal(["title"], wire.SearchFields);
        Assert.Equal(["title"], wire.HighlightFields);
        Assert.Equal("title", Assert.Single(wire.Sort).Field);
        Assert.Equal(Autogenerated.SortOrder.Desc, wire.Sort[0].Order);
        Assert.Equal(ulong.MaxValue, result.TotalHits);
        Assert.Equal(TotalHitsRelation.LowerBound, result.TotalHitsRelation);
        Assert.Equal("next", result.ContinuationToken);
        var hit = Assert.Single(result.Hits);
        Assert.Equal(new Book("Dapr"), hit.Document.Content);
        Assert.Equal(.75, hit.Score);
        Assert.Equal("<em>Dapr</em>", hit.Highlights["title"]);
    }

    [Fact]
    public async Task SearchPreservesOmittedAndExplicitDefaultFieldsAndNativeQuery()
    {
        var invoker = new SearchCallInvoker { Response = new Autogenerated.SearchResponseAlpha1() };
        using var client = CreateClient(invoker);
        var result = await client.SearchAsync<Book>("store", "books", cancellationToken: Ct);
        Assert.Null(Assert.IsType<Autogenerated.SearchRequestAlpha1>(invoker.Request).Query);
        Assert.Null(result.TotalHits);
        Assert.Null(result.ContinuationToken);
        Assert.Empty(result.Hits);
        Assert.Equal(TotalHitsRelation.Unspecified, result.TotalHitsRelation);

        await client.SearchAsync<Book>("store", "books", new SearchQuery(), cancellationToken: Ct);
        var query = Assert.IsType<Autogenerated.SearchRequestAlpha1>(invoker.Request).Query;
        Assert.Equal(Autogenerated.SearchQuery.KindOneofCase.None, query.KindCase);
        Assert.False(query.HasTopK);
        Assert.False(query.HasIncludeContent);
        Assert.False(query.HasContinuationToken);
        Assert.Null(query.Filter);

        invoker.Response = new Autogenerated.SearchResponseAlpha1 { TotalHits = 0, ContinuationToken = "" };
        result = await client.SearchAsync<Book>("store", "books",
            new SearchQuery
            {
                Native = JsonSerializer.SerializeToElement(new { q = "Dapr" }),
                TopK = 0,
                IncludeContent = false,
                ContinuationToken = ""
            }, cancellationToken: Ct);
        query = Assert.IsType<Autogenerated.SearchRequestAlpha1>(invoker.Request).Query;
        Assert.Equal(Autogenerated.SearchQuery.KindOneofCase.Native, query.KindCase);
        Assert.Equal("Dapr", query.Native.Fields["q"].StringValue);
        Assert.True(query.HasTopK);
        Assert.True(query.HasIncludeContent);
        Assert.True(query.HasContinuationToken);
        Assert.Equal(0UL, result.TotalHits);
        Assert.Equal("", result.ContinuationToken);
    }

