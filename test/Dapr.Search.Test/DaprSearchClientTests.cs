    [Theory]
    [InlineData(StatusCode.NotFound)]
    [InlineData(StatusCode.DeadlineExceeded)]
    [InlineData(StatusCode.Unimplemented)]
    [InlineData(StatusCode.Cancelled)]
    public async Task RpcErrorsAreWrappedWithoutLosingStatus(StatusCode code)
    {
        var rpc = new RpcException(new Status(code, "provider failure"));
        var invoker = new SearchCallInvoker { Handler = _ => Task.FromException<object>(rpc) };
        using var client = CreateClient(invoker);
        foreach (var operation in Operations(client, "s", "i"))
        {
            var exception = await Assert.ThrowsAsync<DaprException>(operation);
            Assert.Same(rpc, exception.InnerException);
        }

        Assert.Equal(8, invoker.DisposeCount);
    }

    [Fact]
    public async Task PreCanceledTokenPreventsEveryRpc()
    {
        using var cts = CancellationTokenSource.CreateLinkedTokenSource(Ct);
        cts.Cancel();
        var invoker = new SearchCallInvoker();
        using var client = CreateClient(invoker);
        foreach (var operation in Operations(client, "s", "i", cts.Token))
            await Assert.ThrowsAnyAsync<OperationCanceledException>(operation);
        Assert.Null(invoker.Request);
    }

    [Fact]
    public async Task RemoteCallerCancellationIsNotConvertedToSuccess()
    {
        using var cts = CancellationTokenSource.CreateLinkedTokenSource(Ct);
        var invoker = new SearchCallInvoker
        {
            Handler = _ =>
            {
                cts.Cancel();
                return Task.FromException<object>(new RpcException(new Status(StatusCode.Cancelled, "cancelled")));
            }
        };
        using var client = CreateClient(invoker);
        var error = await Assert.ThrowsAnyAsync<OperationCanceledException>(() =>
            client.SearchAsync<Book>("s", "i", cancellationToken: cts.Token));
        Assert.Equal(cts.Token, error.CancellationToken);
        Assert.Equal(1, invoker.DisposeCount);
    }

