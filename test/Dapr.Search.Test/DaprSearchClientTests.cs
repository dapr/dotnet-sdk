    [Fact]
    public async Task IndexLifecycleMapsRequestsAndResponses()
    {
        var invoker = new SearchCallInvoker { Response = new Empty() };
        using var client = CreateClient(invoker);
        await client.CreateIndexAsync("store", "books", Metadata, Ct);
        var create = Assert.IsType<Autogenerated.CreateIndexRequestAlpha1>(invoker.Request);
        Assert.Equal(("store", "books", "value"), (create.StoreName, create.Index, create.Metadata["setting"]));
        Assert.Equal("/dapr.proto.runtime.v1.Dapr/CreateIndexAlpha1", invoker.Method);
        Assert.Equal(Ct, invoker.Options.CancellationToken);
        Assert.Contains(invoker.Options.Headers!, h => h.Key == "dapr-api-token" && h.Value == "test-token");
        Assert.Contains(invoker.Options.Headers!, h => h.Key == "user-agent");

        var indexResponse =
            new Autogenerated.GetIndexResponseAlpha1 { Index = "books", DocumentCount = ulong.MaxValue };
        indexResponse.Properties.Add("setting", "original");
        invoker.Response = indexResponse;
        var index = await client.GetIndexAsync("store", "books", Metadata, Ct);
        var get = Assert.IsType<Autogenerated.GetIndexRequestAlpha1>(invoker.Request);
        Assert.Equal(("store", "books", "value"), (get.StoreName, get.Index, get.Metadata["setting"]));
        Assert.Equal("/dapr.proto.runtime.v1.Dapr/GetIndexAlpha1", invoker.Method);
        Assert.Equal(ulong.MaxValue, index.DocumentCount);
        Assert.Equal("books", index.Index);
        indexResponse.Properties["setting"] = "changed";
        Assert.Equal("original", index.Properties["setting"]);

        invoker.Response = new Autogenerated.ListIndexesResponseAlpha1 { Indexes = { "books", "movies" } };
        Assert.Equal(["books", "movies"], await client.ListIndexesAsync("store", Metadata, Ct));
        var list = Assert.IsType<Autogenerated.ListIndexesRequestAlpha1>(invoker.Request);
        Assert.Equal(("store", "value"), (list.StoreName, list.Metadata["setting"]));
        Assert.Equal("/dapr.proto.runtime.v1.Dapr/ListIndexesAlpha1", invoker.Method);

        invoker.Response = new Empty();
        await client.DeleteIndexAsync("store", "books", Metadata, Ct);
        var delete = Assert.IsType<Autogenerated.DeleteIndexRequestAlpha1>(invoker.Request);
        Assert.Equal(("store", "books", "value"), (delete.StoreName, delete.Index, delete.Metadata["setting"]));
        Assert.Equal("/dapr.proto.runtime.v1.Dapr/DeleteIndexAlpha1", invoker.Method);
        Assert.Equal(4, invoker.DisposeCount);
    }

    [Theory]
    [InlineData(IndexAck.Queued)]
    [InlineData(IndexAck.Completed)]
    public async Task IndexDocumentsPreservesAcknowledgementsAndRichFailures(IndexAck ack)
    {
        var error = new Google.Rpc.Status { Code = 3, Message = "Not an object" };
        error.Details.Add(new Any
        {
            TypeUrl = "type.googleapis.com/google.rpc.ErrorInfo", Value = ByteString.CopyFrom([1, 2, 3])
        });
        var response = new Autogenerated.IndexDocumentsResponseAlpha1
        {
            Ack = (Autogenerated.IndexAck)ack,
            FailedItems = { new Autogenerated.FailedItem { Id = "bad", Error = error } }
        };
        var invoker = new SearchCallInvoker { Response = response };
        using var client = CreateClient(invoker);
        var result = await client.IndexDocumentsAsync("store", "books",
            new[] { new SearchDocument<Book>("1", new Book("Dapr"), Metadata) }, metadata: Metadata,
            cancellationToken: Ct);
        var request = Assert.IsType<Autogenerated.IndexDocumentsRequestAlpha1>(invoker.Request);
        Assert.Equal(("store", "books", "value"), (request.StoreName, request.Index, request.Metadata["setting"]));
        Assert.Equal("/dapr.proto.runtime.v1.Dapr/IndexDocumentsAlpha1", invoker.Method);
        Assert.Null(request.Options);
        var document = Assert.Single(request.Documents);
        Assert.Equal("1", document.Id);
        Assert.Equal("""{"title":"Dapr"}""", document.Content.ToStringUtf8());
        Assert.Equal("value", document.Metadata["setting"]);
        Assert.Equal(ack, result.Ack);
        var failure = Assert.Single(result.FailedItems);
        Assert.Equal(("bad", 3, "Not an object"), (failure.Id, failure.ErrorCode, failure.ErrorMessage));
        var detail = Assert.Single(failure.Details);
        Assert.Equal("type.googleapis.com/google.rpc.ErrorInfo", detail.TypeUrl);
        Assert.Equal(new byte[] { 1, 2, 3 }, detail.Value.ToArray());
    }

