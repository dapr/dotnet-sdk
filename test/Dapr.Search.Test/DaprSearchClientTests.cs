    [Fact]
    public async Task DisposedClientRejectsOperations()
    {
        var invoker = new SearchCallInvoker();
        var client = CreateClient(invoker);
        client.Dispose();
        client.Dispose();
        foreach (var operation in Operations(client, "s", "i"))
            await Assert.ThrowsAsync<ObjectDisposedException>(operation);
        Assert.Null(invoker.Request);
    }

    private static IEnumerable<Func<Task>> Operations(DaprSearchClient client, string store, string index,
        CancellationToken? token = null)
    {
        var ct = token ?? Ct;
        yield return () => client.ListIndexesAsync(store, cancellationToken: ct);
        yield return () => client.CreateIndexAsync(store, index, cancellationToken: ct);
        yield return () => client.GetIndexAsync(store, index, cancellationToken: ct);
        yield return () => client.DeleteIndexAsync(store, index, cancellationToken: ct);
        yield return () => client.IndexDocumentsAsync<Book>(store, index, [], cancellationToken: ct);
        yield return () => client.GetDocumentsAsync<Book>(store, index, [], cancellationToken: ct);
        yield return () => client.DeleteDocumentsAsync(store, index, [], cancellationToken: ct);
        yield return () => client.SearchAsync<Book>(store, index, cancellationToken: ct);
    }
