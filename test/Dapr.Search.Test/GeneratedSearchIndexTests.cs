using System.Text.Json;
using Dapr.Common.Serialization;
using Dapr.Search.Extensions;
using Google.Protobuf.WellKnownTypes;
using Grpc.Core;
using Microsoft.Extensions.DependencyInjection;
using Autogenerated = Dapr.Client.Autogen.Grpc.v1;

namespace Dapr.Search.Test;

[SearchIndex("generated-store", "books")]
internal partial interface IBookSearch : IDaprSearchIndex<Book>;

public sealed class GeneratedSearchIndexTests
{
    [Fact]
    public async Task GeneratedWrapperForwardsEveryOperationAndPreservesOptions()
    {
        var invoker = new SearchCallInvoker { Response = new Empty() };
        using var client = new DaprSearchGrpcClient(new Autogenerated.Dapr.DaprClient(invoker), new HttpClient(),
            new JsonDaprSerializer(new JsonSerializerOptions(JsonSerializerDefaults.Web)));
        var services = new ServiceCollection();
        services.AddSingleton<DaprSearchClient>(client);
        var builder = new DaprSearchBuilder(services);
        Assert.Same(builder, builder.AddBookSearch());
        using var provider = services.BuildServiceProvider();
        var index = provider.GetRequiredService<IBookSearch>();
        var ct = TestContext.Current.CancellationToken;
        var metadata = new Dictionary<string, string> { ["setting"] = "value" };
        var wait = new IndexingOptions
        {
            Mode = IndexingMode.WaitForCompletion,
            WaitTimeout = TimeSpan.FromSeconds(5),
            OnWaitTimeout = IndexingWaitTimeoutAction.FailRequest
        };

        await index.CreateIndexAsync(metadata, ct);
        var create = Assert.IsType<Autogenerated.CreateIndexRequestAlpha1>(invoker.Request);
        Assert.Equal(("generated-store", "books", "value"), (create.StoreName, create.Index, create.Metadata["setting"]));
        Assert.Equal(ct, invoker.Options.CancellationToken);

        invoker.Response = new Autogenerated.GetIndexResponseAlpha1 { Index = "books", DocumentCount = 2 };
        Assert.Equal(2UL, (await index.GetIndexAsync(metadata, ct)).DocumentCount);
        var get = Assert.IsType<Autogenerated.GetIndexRequestAlpha1>(invoker.Request);
        Assert.Equal(("generated-store", "books", "value"), (get.StoreName, get.Index, get.Metadata["setting"]));

        invoker.Response = new Autogenerated.IndexDocumentsResponseAlpha1
        {
            Ack = Autogenerated.IndexAck.Queued,
            FailedItems = { new Autogenerated.FailedItem { Id = "bad", Error = new Google.Rpc.Status { Code = 3, Message = "bad content" } } }
        };
        var write = await index.IndexDocumentsAsync([new SearchDocument<Book>("1", new Book("Dapr"), metadata)], wait, metadata, ct);
        Assert.Equal(IndexAck.Queued, write.Ack);
        Assert.Equal("bad", Assert.Single(write.FailedItems).Id);
        var documents = Assert.IsType<Autogenerated.IndexDocumentsRequestAlpha1>(invoker.Request);
        Assert.Equal(("generated-store", "books", "value"), (documents.StoreName, documents.Index, documents.Metadata["setting"]));
        Assert.Equal(wait.WaitTimeout, documents.Options.WaitTimeout.ToTimeSpan());
        Assert.Equal("""{"title":"Dapr"}""", Assert.Single(documents.Documents).Content.ToStringUtf8());
        Assert.Equal("value", documents.Documents[0].Metadata["setting"]);

        invoker.Response = new Autogenerated.GetDocumentsResponseAlpha1 { Documents = { documents.Documents[0] } };
        Assert.Equal(new Book("Dapr"), Assert.Single(await index.GetDocumentsAsync(["1"], true, metadata, ct)).Content);
        var read = Assert.IsType<Autogenerated.GetDocumentsRequestAlpha1>(invoker.Request);
        Assert.Equal(("generated-store", "books", "value"), (read.StoreName, read.Index, read.Metadata["setting"]));
        Assert.Equal(["1"], read.Ids);
        Assert.True(read.IncludeContent);

        invoker.Response = new Autogenerated.SearchResponseAlpha1
        {
            ContinuationToken = "next",
            TotalHits = 1,
            TotalHitsRelation = Autogenerated.TotalHitsRelation.Exact,
            Hits = { new Autogenerated.SearchHit { Document = documents.Documents[0], Score = .9 } }
        };
        var results = await index.SearchAsync(new SearchQuery { Text = "Dapr", ContinuationToken = "previous", IncludeContent = true }, metadata, ct);
        Assert.Equal(new Book("Dapr"), Assert.Single(results.Hits).Document.Content);
        Assert.Equal("next", results.ContinuationToken);
        var search = Assert.IsType<Autogenerated.SearchRequestAlpha1>(invoker.Request);
        Assert.Equal(("generated-store", "books", "value"), (search.StoreName, search.Index, search.Metadata["setting"]));
        Assert.Equal("previous", search.Query.ContinuationToken);
        Assert.Equal("Dapr", search.Query.Text);

        invoker.Response = new Autogenerated.DeleteDocumentsResponseAlpha1 { Ack = Autogenerated.IndexAck.Completed };
        Assert.Equal(IndexAck.Completed, await index.DeleteDocumentsAsync(["1"], wait, metadata, ct));
        var delete = Assert.IsType<Autogenerated.DeleteDocumentsRequestAlpha1>(invoker.Request);
        Assert.Equal(("generated-store", "books", "value"), (delete.StoreName, delete.Index, delete.Metadata["setting"]));
        Assert.Equal(["1"], delete.Ids);
        Assert.Equal(documents.Options, delete.Options);

        invoker.Response = new Empty();
        await index.DeleteIndexAsync(metadata, ct);
        var deleteIndex = Assert.IsType<Autogenerated.DeleteIndexRequestAlpha1>(invoker.Request);
        Assert.Equal(("generated-store", "books", "value"), (deleteIndex.StoreName, deleteIndex.Index, deleteIndex.Metadata["setting"]));
        Assert.Equal(ct, invoker.Options.CancellationToken);

        invoker.Handler = _ => Task.FromException<object>(new RpcException(new Status(StatusCode.NotFound, "missing")));
        var error = await Assert.ThrowsAsync<DaprException>(() => index.GetIndexAsync(cancellationToken: ct));
        Assert.Equal(StatusCode.NotFound, Assert.IsType<RpcException>(error.InnerException).StatusCode);
        using var cancellation = CancellationTokenSource.CreateLinkedTokenSource(ct);
        cancellation.Cancel();
        await Assert.ThrowsAnyAsync<OperationCanceledException>(() => index.SearchAsync(cancellationToken: cancellation.Token));
    }

    [Theory]
    [InlineData(ServiceLifetime.Singleton)]
    [InlineData(ServiceLifetime.Scoped)]
    [InlineData(ServiceLifetime.Transient)]
    public void GeneratedRegistrationFollowsUnderlyingClientLifetime(ServiceLifetime lifetime)
    {
        var services = new ServiceCollection();
        services.AddDaprSearchClient(lifetime: lifetime).AddBookSearch();
        Assert.Equal(lifetime, Assert.Single(services, d => d.ServiceType == typeof(IBookSearch)).Lifetime);
        using var provider = services.BuildServiceProvider(new ServiceProviderOptions { ValidateScopes = true, ValidateOnBuild = true });
        using var firstScope = provider.CreateScope();
        using var secondScope = provider.CreateScope();
        var first = firstScope.ServiceProvider.GetRequiredService<IBookSearch>();
        var repeated = firstScope.ServiceProvider.GetRequiredService<IBookSearch>();
        var other = secondScope.ServiceProvider.GetRequiredService<IBookSearch>();
        Assert.Equal(lifetime != ServiceLifetime.Transient, ReferenceEquals(first, repeated));
        Assert.Equal(lifetime == ServiceLifetime.Singleton, ReferenceEquals(first, other));
        Assert.False(first is IDisposable);
    }

    [Fact]
    public void RegistrationRequiresBuilderAndUnderlyingClient()
    {
        Assert.Throws<ArgumentNullException>(() => IBookSearchSearchIndexExtensions.AddBookSearch(null!));
        Assert.Throws<InvalidOperationException>(() => new DaprSearchBuilder(new ServiceCollection()).AddBookSearch());
    }
}
